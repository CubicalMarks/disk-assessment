const assert = require('node:assert/strict');
const {color, index, Navigation} = require('./ui-model.js');
const leaf = {path:'/root/a/file',kind:'file',bytes:12};
const a = {path:'/root/a',kind:'directory',bytes:12,children:[leaf]};
const b = {path:'/root/b',kind:'directory',bytes:20,children:[]};
const root = {path:'/root',kind:'directory',bytes:32,children:[a,b]};
const data = {tree:root};
const model = index(data);
assert.deepEqual(model.chain(leaf.path).map(n=>n.path),['/root','/root/a','/root/a/file']);
assert.equal(model.chain('/missing'), null);
const nav = new Navigation([root]);
nav.visit([root,a]);
nav.visit([root,a]);
assert.equal(nav.entries.length,2,'Repeated selection must not create a history entry');
assert.equal(nav.back().at(-1).path,root.path);
assert.equal(nav.canForward,true);
assert.equal(nav.forward().at(-1).path,a.path);
nav.back();nav.visit([root,b]);
assert.equal(nav.canForward,false,'New navigation must discard the forward branch');
const copy=nav.current;copy.pop();
assert.equal(nav.current.at(-1).path,b.path,'Callers must not alter stored history');
assert.equal(color(a.path),color(a.path));
assert.match(color(a.path),/^#[a-f\d]{6}$/i);
assert.equal(root.bytes,32);
console.log('Report UX: item indexing, ancestor navigation, back/forward history, stable colors and unchanged scan data passed.');
